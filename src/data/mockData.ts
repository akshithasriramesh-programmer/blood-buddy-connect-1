// Check if a donor with `donorGroup` can donate to patient with `patientGroup`
export function isCompatible(donorGroup: BloodGroup, patientGroup: BloodGroup): boolean {
  return BLOOD_COMPATIBILITY[donorGroup].canDonateTo.includes(patientGroup);
}

// Get all blood groups that can donate to this patient group
export function getCompatibleDonorsFor(patientGroup: BloodGroup): BloodGroup[] {
  return BLOOD_COMPATIBILITY[patientGroup].canReceiveFrom;
}

